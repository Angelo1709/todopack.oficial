import assert from "node:assert/strict"
import { DELIVERY_SETTINGS_DEFAULTS as defaults,validateDeliverySettings,deliveryInstant,deliveryCutoff,deliveryWindow,canBookDelivery,dateInArgentina,nextDelivery,formatCutoff,validDeliveryDate } from "../lib/delivery-schedule.ts"

const day="2026-10-07"
const at=time=>deliveryInstant(day,time)
assert.equal(new Date(at("12:00")).toISOString(),"2026-10-07T15:00:00.000Z")
assert.equal(validateDeliverySettings(defaults).ok,true)
assert.equal(deliveryCutoff(defaults,day,"mediodia"),at("11:00"))
assert.equal(deliveryCutoff(defaults,day,"noche"),at("18:00"))
assert.equal(canBookDelivery(defaults,day,"mediodia",at("11:00")-1),true)
assert.equal(canBookDelivery(defaults,day,"mediodia",at("11:00")),false)
assert.equal(canBookDelivery(defaults,day,"mediodia",at("11:30")),false)
assert.equal(canBookDelivery(defaults,day,"noche",at("18:00")-1),true)
assert.equal(canBookDelivery(defaults,day,"noche",at("18:00")),false)
assert.deepEqual(nextDelivery(defaults,at("10:59")),{date:day,slot:"mediodia"})
assert.deepEqual(nextDelivery(defaults,at("11:30")),{date:day,slot:"noche"})
assert.deepEqual(nextDelivery(defaults,at("18:00")),{date:"2026-10-08",slot:"mediodia"})
assert.deepEqual(nextDelivery(defaults,Date.parse("2026-12-31T23:00:00-03:00")),{date:"2027-01-01",slot:"mediodia"})
assert.equal(canBookDelivery(defaults,"2026-10-06","noche",at("10:00")),false)
assert.equal(canBookDelivery(defaults,"2026-10-08","mediodia",at("23:00")),true)
assert.equal(dateInArgentina(Date.parse("2026-10-08T02:59:00Z")),day)
assert.equal(dateInArgentina(Date.parse("2026-10-08T03:00:00Z")),"2026-10-08")
assert.equal(validateDeliverySettings({...defaults,deliveryLeadMinutes:"0"}).ok,true)
assert.equal(canBookDelivery({...defaults,deliveryLeadMinutes:"0"},day,"mediodia",at("12:00")-1),true)
assert.equal(canBookDelivery({...defaults,deliveryLeadMinutes:"0"},day,"mediodia",at("12:00")),false)
assert.equal(validateDeliverySettings({...defaults,deliveryNightEnd:"02:00"}).ok,true)
assert.equal(deliveryWindow({...defaults,deliveryNightEnd:"02:00"},"noche"),"19:00–02:00 (termina al día siguiente)")
assert.equal(validateDeliverySettings({...defaults,deliveryNightEnd:"13:00"}).ok,false)
assert.equal(validateDeliverySettings({...defaults,deliveryNightStart:"14:00"}).ok,false)
assert.equal(validateDeliverySettings({...defaults,deliveryMiddayEnd:"12:00"}).ok,false)
assert.equal(validateDeliverySettings({...defaults,deliveryMiddayStart:"24:00"}).ok,false)
assert.equal(validateDeliverySettings({...defaults,deliveryLeadMinutes:"-1"}).ok,false)
assert.equal(validateDeliverySettings({...defaults,deliveryLeadMinutes:"1.5"}).ok,false)
assert.equal(validateDeliverySettings({...defaults,deliveryLeadMinutes:"10081"}).ok,false)
assert.equal(validateDeliverySettings({...defaults,deliveryLeadMinutes:""}).ok,false)
assert.equal(validateDeliverySettings({}).ok,false)
assert.equal(validDeliveryDate("2026-02-31"),false)
assert.equal(validDeliveryDate("2028-02-29"),true)
const longLead={...defaults,deliveryLeadMinutes:"10080"}
assert.equal(nextDelivery(longLead,at("12:00")).date,"2026-10-14")
const previousDay={...defaults,deliveryMiddayStart:"01:00",deliveryMiddayEnd:"03:00",deliveryLeadMinutes:"120"}
assert.equal(formatCutoff(deliveryCutoff(previousDay,day,"mediodia"),day),"23:00 del 06/10/2026")
console.log("OK: límites exactos, próximo turno, medianoche argentina, fin de año, anticipación 0–7 días, horarios nocturnos y validación.")
